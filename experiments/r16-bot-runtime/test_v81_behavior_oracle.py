def adapter_outcomes(sample):
    outputs = {}
    for key, check in adapter.CHECKS.items():
        try:
            outputs[key] = "PASS" if check(sample) else "FAIL"
        except (KeyError, ValueError, TypeError, AssertionError,
                AttributeError, OverflowError, RecursionError):
            outputs[key] = "UNVERIFIED"
    return outputs


class OriginalBehaviorVectors(unittest.TestCase):
    def test_18_baseline_rules(self):
        results = adapter_outcomes(fixture())
        self.assertEqual(18, len(results))
        self.assertEqual({"PASS"}, set(results.values()))

    def test_29_mutations_against_original_observations(self):
        self.assertEqual(29, len(MUTATIONS))
        self.assertEqual(set(MUTATIONS), set(ORIGINAL_NON_PASS))
        self.assertEqual(18, len(adapter.CHECKS))
        for name, break_case in MUTATIONS.items():
            with self.subTest(case=name):
                sample = fixture()
                break_case(sample)
                observed = adapter_outcomes(sample)
                oracle = ORIGINAL_NON_PASS[name]
                hardened = INTENTIONAL_HARDENING.get(name, {})
                # Each individual rule's outcome is checked, not only an
                # aggregate PASS count. The Unicode deviations are explicit.
                for rule in adapter.CHECKS:
                    expected = hardened.get(rule, oracle.get(rule, "PASS"))
                    self.assertEqual(expected, observed[rule],
                                     f"{name} / {rule}")

    def test_unicode_deviation_is_not_silently_claimed_equal(self):
        self.assertEqual({"unicode_slack_ts", "non_ascii_decimal_digits"},
                         set(INTENTIONAL_HARDENING))
        for name, differences in INTENTIONAL_HARDENING.items():
            with self.subTest(name=name):
                self.assertEqual({"L07": "FAIL", "L08": "FAIL"}, differences)
                self.assertEqual({}, ORIGINAL_NON_PASS[name])

    def test_slack_microsecond_order_fail_closed(self):
        # Deliberate security hardening: the original v8.1 uses float(ts)
        # and accepts this reversed order near the end of 10-digit epochs.
        sample = fixture()
        sample["slack"]["messages"][0].update(
            ts="9999999999.000001", thread_ts="9999999999.000002")
        outcomes = adapter_outcomes(sample)
        self.assertEqual("PASS", outcomes["L07"])
        self.assertEqual("FAIL", outcomes["L08"])

    def test_slack_microsecond_valid_order(self):
        sample = fixture()
        sample["slack"]["messages"][0].update(
            ts="9999999999.000002", thread_ts="9999999999.000001")
        outcomes = adapter_outcomes(sample)
        self.assertEqual("PASS", outcomes["L08"])

    def test_l08_malformed_comparable_timestamps_remain_unverified(self):
        # All these inputs used to be FAIL because float() could parse them.
        for changes in (
            {"ts": "1700000000.00001"},
            {"thread_ts": "not-a-ts"},
            {"thread_ts": "1700000000.00001"},
            {"ts": "1.7e9"},
        ):
            with self.subTest(changes=changes):
                sample = fixture()
                sample["slack"]["messages"][0].update(changes)
                self.assertEqual("UNVERIFIED", adapter_outcomes(sample)["L08"])

    def test_l08_malformed_earlier_message_does_not_hide_valid_order(self):
        sample = fixture()
        sample["slack"]["messages"][0]["ts"] = "1.7e9"
        sample["slack"]["messages"].append({
            "channel": "C0000000000", "text": "synthetic",
            "ts": "1700000000.000002", "thread_ts": "1700000000.000001"
        })
        self.assertEqual("UNVERIFIED", adapter_outcomes(sample)["L08"])

    def test_l08_proven_reverse_dominates_unverified_message(self):
        sample = fixture()
        sample["slack"]["messages"][0]["ts"] = "1.7e9"
        sample["slack"]["messages"].append({
            "channel": "C0000000000", "text": "synthetic",
            "ts": "9999999999.000001", "thread_ts": "9999999999.000002"
        })
        self.assertEqual("FAIL", adapter_outcomes(sample)["L08"])

    def test_l08_valid_message_without_thread_is_not_reversed(self):
        sample = fixture()
        sample["slack"]["messages"][0].pop("thread_ts")
        self.assertEqual("PASS", adapter_outcomes(sample)["L08"])

